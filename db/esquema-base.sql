-- ============================================================================
-- ESQUEMA BASE de SIM WEB — solo ESTRUCTURA, cero datos
-- ----------------------------------------------------------------------------
-- Por qué existe: los 63 archivos de db/ son INCREMENTALES y crean 59 tablas
-- (ia_*, mensualidad_*, cronograma_*, sim_control_*, campeonato_checkouts,
-- y las de configuración comercial posteriores). Las 47 tablas
-- de negocio originales —reservas, turnos_stand, campeonatos, gift_cards, todo
-- fin_*, colectivo_*, empresa_*, los brackets— se crearon fuera del repositorio al
-- principio del proyecto y existían SOLO en Producción. Sin ellas no se puede
-- levantar una base de pruebas, y por eso las 53 suites mutantes solo podían correr
-- contra la base real.
--
-- Cómo se obtuvo: introspección de SOLO LECTURA del catálogo de Producción
-- (pg_catalog / information_schema). NO es un dump de datos: no contiene una sola
-- fila, ni clientes, ni teléfonos, ni correos, ni pagos.
--
-- Orden del archivo (importante en una base vacía):
--   1. extensiones      2. tablas sin constraints
--   3. claves primarias, únicas y checks                4. claves foráneas
--   5. índices          6. row level security
--
-- Destino: la base LOCAL de pruebas. Aplicarlo a Producción sería un no-op
-- (todo es `if not exists` / aditivo), pero no es su propósito.
-- ============================================================================

-- ── 1. Extensiones ─────────────────────────────────────────────────────────
create extension if not exists pgcrypto;
create extension if not exists "uuid-ossp";
create extension if not exists btree_gist;

-- ── 1b. Tipos propios ───────────────────────────────────────────────────────
-- cronograma_timerange es un rango sobre `time`. Crearlo da automáticamente sus
-- constructores (cronograma_timerange(...), cronograma_timemultirange(...)), que en
-- Producción aparecen como funciones del esquema public pero no se escriben a mano.
do $$
begin
  if not exists (select 1 from pg_type t join pg_namespace n on n.oid=t.typnamespace
                 where n.nspname='public' and t.typname='cronograma_timerange') then
    create type public.cronograma_timerange as range (subtype = time without time zone);
  end if;
end $$;

