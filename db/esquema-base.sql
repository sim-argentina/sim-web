CREATE OR REPLACE FUNCTION public.cancelar_reserva_empresa(p_reserva_id bigint, p_liberar_codigo boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE v_res public.reservas%ROWTYPE;
BEGIN
  SELECT * INTO v_res FROM public.reservas WHERE id = p_reserva_id AND origen = 'empresa' FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  IF v_res.estado = 'cancelada' THEN RETURN true; END IF;
  UPDATE public.reserva_slots SET estado = 'cancelada' WHERE reserva_id = p_reserva_id;
  UPDATE public.reservas SET estado = 'cancelada' WHERE id = p_reserva_id;
  IF p_liberar_codigo AND v_res.empresa_codigo_id IS NOT NULL THEN
    UPDATE public.empresa_codigos
       SET usos_actuales = greatest(usos_actuales - 1, 0), estado = 'disponible', updated_at = now()
     WHERE id = v_res.empresa_codigo_id;
    UPDATE public.empresa_codigo_usos SET estado = 'cancelado' WHERE reserva_id = p_reserva_id;
  END IF;
  RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.crear_bloqueo_reserva(p_fecha date, p_todo_el_dia boolean, p_hora_inicio text, p_hora_fin text, p_simulador text, p_motivo text)
 RETURNS SETOF bloqueos_reservas
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('reserva-slot:' || p_fecha)::bigint);
  RETURN QUERY
    INSERT INTO public.bloqueos_reservas (fecha, todo_el_dia, hora_inicio, hora_fin, simulador, motivo, activo)
    VALUES (p_fecha, p_todo_el_dia, p_hora_inicio, p_hora_fin, p_simulador, p_motivo, true)
    RETURNING *;
END;
$function$;

CREATE OR REPLACE FUNCTION public.mensualidad_bloques_coherentes(p_hora text, p_duracion integer, p_slots text[])
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  select p_hora ~ '^\d{2}:\d{2}$'
     and p_duracion in (15, 30, 45, 60)
     and p_slots is not null
     and array_length(p_slots, 1) = p_duracion / 15
     and p_slots = (
       select array_agg(
         lpad((((split_part(p_hora, ':', 1)::int * 60 + split_part(p_hora, ':', 2)::int) + i * 20) / 60)::text, 2, '0')
         || ':' ||
         lpad((((split_part(p_hora, ':', 1)::int * 60 + split_part(p_hora, ':', 2)::int) + i * 20) % 60)::text, 2, '0')
         order by i)
       from generate_series(0, p_duracion / 15 - 1) as i
     );
$function$;

